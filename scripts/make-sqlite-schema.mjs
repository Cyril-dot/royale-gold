// Generates prisma/schema.sqlite.prisma from prisma/schema.prisma.
// DEV-ONLY stand-in: this VM has no Postgres and no Docker, so local
// verification runs against SQLite. Production ALWAYS uses the Postgres
// schema (prisma/schema.prisma) via DATABASE_URL. Differences, all
// documented in README.md:
//   - provider sqlite (not postgresql)
//   - Decimal -> Float (SQLite has no Decimal; money is rounded to 2dp
//     in code before storage, so values stay exact to the pesewa)
//   - enum Role -> String (SQLite has no enums)
//   - @db.Decimal(...) attributes stripped
//   - no other changes
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8");

let out = src
  .replace('provider = "postgresql"', 'provider = "sqlite"')
  .replace(/ @db\.Decimal\(\d+, \d+\)/g, "")
  .replace(/Decimal/g, "Float")
  .replace("role             Role     @default(user)", 'role             String   @default("user")')
  .replace(
    /enum Role \{\n  owner\n  admin\n  user\n\}\n\n/,
    "",
  )
  .replace(
    "// Prisma 7: the connection URL lives in prisma.config.ts (datasource.url),\n  // not here. The runtime client gets it via the pg adapter (src/lib/prisma.ts).",
    "// DEV-ONLY sqlite stand-in. Generated by scripts/make-sqlite-schema.mjs — do not edit by hand.",
  );

writeFileSync(new URL("../prisma/schema.sqlite.prisma", import.meta.url), out);
console.log("Wrote prisma/schema.sqlite.prisma");
